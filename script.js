async function loadSystemAdminData(language) {
  if (!systemCompanyList) {
    return;
  }

  const auth = getStoredAuth();
  const role = getStoredUserRole();
  if (!auth || !isSystemAdministratorRole(role)) {
    window.location.href = auth ? getDefaultPageForRole(role) : "login.html";
    return;
  }

  const profileResult = await apiRequest("/api/auth/me", { auth: true });
  if (!profileResult.ok) {
    clearAuth();
    systemAdminDataLoadedFromApi = false;
    window.location.href = "login.html";
    return;
  }

  const fullName = `${getField(profileResult.data, "firstName") || ""} ${getField(profileResult.data, "lastName") || ""}`.trim();
  setSystemAdminMessage(
    translations[language].systemAdmin.session.replace("{name}", fullName || getField(profileResult.data, "email") || "-"),
  );

  const companiesResult = await apiRequest("/api/system/companies", { auth: true });
  if (!companiesResult.ok) {
    systemAdminDataLoadedFromApi = false;
    currentSystemCompanies = [];
    setSystemAdminMessage(companiesResult.error || translations[language].systemAdmin.apiFallback, "error");
    renderSystemAdmin(language, []);
    return;
  }

  systemAdminDataLoadedFromApi = true;
  currentSystemCompanies = companiesResult.data || [];
  renderSystemAdmin(language, currentSystemCompanies);
}

async function loadSystemCompanyData(language) {
  if (!systemCompanyPeopleList) {
    return;
  }

  const auth = getStoredAuth();
  const role = getStoredUserRole();
  if (!auth || !isSystemAdministratorRole(role)) {
    window.location.href = auth ? getDefaultPageForRole(role) : "login.html";
    return;
  }

  const companyId = new URLSearchParams(window.location.search).get("companyId");
  const companyNameFromUrl = new URLSearchParams(window.location.search).get("companyName");
  if (!companyId) {
    window.location.href = "system-admin.html";
    return;
  }

  if (systemCompanyTitle) {
    systemCompanyTitle.textContent = companyNameFromUrl || translations[language].systemAdmin.loadingCompany;
  }

  if (systemCompanySubscription) {
    systemCompanySubscription.textContent = translations[language].systemAdmin.loadingCompany;
  }

  const [companiesResult, usersResult, workersResult] = await Promise.all([
    apiRequest("/api/system/companies", { auth: true }),
    apiRequest(`/api/system/companies/${encodeURIComponent(companyId)}/users`, { auth: true }),
    apiRequest(`/api/system/companies/${encodeURIComponent(companyId)}/workers`, { auth: true }),
  ]);

  if (!companiesResult.ok || !usersResult.ok || !workersResult.ok) {
    currentSystemCompanyUsers = [];
    currentSystemCompanyWorkers = [];
    setSystemAdminMessage(
      usersResult.error || workersResult.error || companiesResult.error || translations[language].systemAdmin.apiFallback,
      "error",
    );
    renderOrganizationUsers(language, [], []);
    return;
  }

  const companies = companiesResult.data || [];
  const company = companies.find((item) => String(getField(item, "id")) === String(companyId));
  currentSystemCompanyUsers = usersResult.data || [];
  currentSystemCompanyWorkers = workersResult.data || [];

  if (systemCompanyTitle) {
    systemCompanyTitle.textContent = company ? getField(company, "name") || "-" : translations[language].systemAdmin.companyDetailsTitle;
  }

  if (systemCompanySubscription) {
    const subscriptionLevel = getField(company, "subscriptionLevel") || "SmallBusiness";
    const peopleCount = buildOrganizationPeople(currentSystemCompanyUsers, currentSystemCompanyWorkers).length;
    systemCompanySubscription.textContent = company
      ? translations[language].systemAdmin.companyPeopleSummary
          .replace("{subscription}", `${translations[language].systemAdmin.subscriptionLevel}: ${getSubscriptionLabel(subscriptionLevel, language)}`)
          .replace("{people}", String(peopleCount))
      : "";
  }

  setSystemAdminMessage(translations[language].systemAdmin.companyDetailsCopy);
  renderOrganizationUsers(language, currentSystemCompanyUsers, currentSystemCompanyWorkers);
}

async function updateOrganizationUserRole(form) {
  if (!getAccessToken()) {
    setOrganizationUserMessage(translations[currentLanguage].platform.roleChangeUnavailable, "error");
    return;
  }

  const userId = form.dataset.userId;
  const select = form.querySelector('select[name="role"]');
  const role = select?.value;
  if (!userId || !role) {
    setOrganizationUserMessage(translations[currentLanguage].platform.roleChangeUnavailable, "error");
    return;
  }

  const endpoint = pageName === "systemCompany"
    ? `/api/system/users/${encodeURIComponent(userId)}/role`
    : `/api/users/${encodeURIComponent(userId)}/role`;

  select.disabled = true;
  setOrganizationUserMessage(translations[currentLanguage].platform.roleChangeWorking);

  const result = await apiRequest(endpoint, {
    method: "PATCH",
    auth: true,
    body: { role },
  });

  select.disabled = false;

  if (!result.ok) {
    setOrganizationUserMessage(result.error || translations[currentLanguage].platform.roleChangeUnavailable, "error");
    if (pageName === "systemCompany") {
      loadSystemCompanyData(currentLanguage);
    } else {
      loadPlatformData(currentLanguage);
    }
    return;
  }

  setOrganizationUserMessage(translations[currentLanguage].platform.roleChangeSuccess, "success");
  if (pageName === "systemCompany") {
    loadSystemCompanyData(currentLanguage);
    return;
  }

  loadPlatformData(currentLanguage);
}

